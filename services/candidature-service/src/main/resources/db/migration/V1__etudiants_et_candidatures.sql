-- Schéma de candidature-service (phase 7 d). Reprend l'état final des tables du monolithe (migrations V1 à V7,
-- consultables au tag v1.0-monolithe) en une seule migration : la base démarre vide, rien à rejouer.

-- Profil étudiant : même id que le compte d'auth-service (créé par la saga d'inscription), pas de clé étrangère
-- vers une autre base
CREATE TABLE etudiant (
    id        BIGINT       PRIMARY KEY,
    email     VARCHAR(255) NOT NULL,
    nom       VARCHAR(100) NOT NULL,
    prenom    VARCHAR(100) NOT NULL,
    ecole     VARCHAR(150) NOT NULL,
    filiere   VARCHAR(150) NOT NULL,
    ville     VARCHAR(100) NOT NULL,
    -- Nom du fichier CV en vigueur (nom UUID, jamais celui envoyé), null tant qu'aucun CV n'est déposé
    chemin_cv VARCHAR(500)
);

CREATE TABLE candidature (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    etudiant_id       BIGINT       NOT NULL REFERENCES etudiant (id),
    -- Offre et entreprise vivent dans offre-service : identifiants sans clé étrangère, plus un instantané pris au
    -- moment de postuler (dénormalisation volontaire, voir Candidature)
    offre_id          BIGINT       NOT NULL,
    entreprise_id     BIGINT       NOT NULL,
    offre_titre       VARCHAR(150) NOT NULL,
    entreprise_nom    VARCHAR(150) NOT NULL,
    offre_ville       VARCHAR(100),
    lettre_motivation TEXT,
    statut            VARCHAR(20)  NOT NULL,
    date_candidature  TIMESTAMPTZ  NOT NULL,
    -- CV figé au moment de postuler : l'entreprise télécharge ce fichier, même si l'étudiant le remplace ensuite
    cv_fichier        VARCHAR(100),
    -- Rempli en phase 8 (Spring AI)
    score_matching    INTEGER,
    CONSTRAINT uk_candidature_etudiant_offre UNIQUE (etudiant_id, offre_id),
    CONSTRAINT ck_candidature_statut CHECK (statut IN ('EN_ATTENTE', 'ENTRETIEN', 'ACCEPTEE', 'REFUSEE')),
    CONSTRAINT ck_candidature_score CHECK (score_matching BETWEEN 0 AND 100)
);

-- Candidatures reçues sur une offre ; propriété vérifiée par entreprise ; un CV remplacé n'est supprimé que si aucune
-- candidature ne le référence (index partiel : seules les lignes avec un CV)
CREATE INDEX idx_candidature_offre ON candidature (offre_id);
CREATE INDEX idx_candidature_entreprise ON candidature (entreprise_id);
CREATE INDEX idx_candidature_cv_fichier ON candidature (cv_fichier) WHERE cv_fichier IS NOT NULL;
