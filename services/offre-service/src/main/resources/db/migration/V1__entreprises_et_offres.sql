-- Base d'offre-service (phase 7 c) : entreprises et offres, reprises du monolithe (V1, V2 et V5 de son schéma).
-- L'id d'une entreprise est celui de son compte dans auth-service (sans clé étrangère : autre base).

CREATE TABLE entreprise (
    id                 BIGINT       PRIMARY KEY,
    -- Copie de l'email du compte, pour les notifications
    email              VARCHAR(255) NOT NULL,
    nom                VARCHAR(150) NOT NULL,
    secteur            VARCHAR(100) NOT NULL,
    ville              VARCHAR(100) NOT NULL,
    description        TEXT,
    statut_validation  VARCHAR(20)  NOT NULL,
    CONSTRAINT ck_entreprise_statut_validation CHECK (statut_validation IN ('EN_ATTENTE', 'VALIDEE', 'REFUSEE'))
);

CREATE INDEX idx_entreprise_statut_validation ON entreprise (statut_validation);

CREATE TABLE offre (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre          VARCHAR(150) NOT NULL,
    description    TEXT         NOT NULL,
    ville          VARCHAR(100) NOT NULL,
    domaine        VARCHAR(100) NOT NULL,
    duree_mois     INTEGER      NOT NULL,
    date_limite    DATE         NOT NULL,
    statut         VARCHAR(20)  NOT NULL,
    entreprise_id  BIGINT       NOT NULL REFERENCES entreprise (id),
    CONSTRAINT ck_offre_duree_mois CHECK (duree_mois BETWEEN 1 AND 12),
    CONSTRAINT ck_offre_statut CHECK (statut IN ('OUVERTE', 'FERMEE'))
);

CREATE INDEX idx_offre_statut ON offre (statut);
CREATE INDEX idx_offre_entreprise ON offre (entreprise_id);

CREATE TABLE offre_technologie (
    offre_id     BIGINT      NOT NULL REFERENCES offre (id) ON DELETE CASCADE,
    technologie  VARCHAR(50) NOT NULL,
    PRIMARY KEY (offre_id, technologie)
);

-- Filtres insensibles à la casse (phase 3) : index sur lower(...)
CREATE INDEX idx_offre_ville_lower ON offre (lower(ville));
CREATE INDEX idx_offre_domaine_lower ON offre (lower(domaine));
CREATE INDEX idx_offre_technologie_lower ON offre_technologie (lower(technologie));
