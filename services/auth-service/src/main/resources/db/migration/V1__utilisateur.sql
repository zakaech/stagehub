-- Base d'auth-service : les comptes seulement (les profils sont dans les services métier).
-- Même définition que dans le monolithe, plus le statut du compte (saga d'inscription).

CREATE TABLE utilisateur (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(255) NOT NULL,
    mot_de_passe   VARCHAR(100) NOT NULL,
    role           VARCHAR(20)  NOT NULL,
    statut         VARCHAR(20)  NOT NULL,
    date_creation  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_utilisateur_email UNIQUE (email),
    CONSTRAINT ck_utilisateur_role CHECK (role IN ('ETUDIANT', 'ENTREPRISE', 'ADMIN')),
    CONSTRAINT ck_utilisateur_statut CHECK (statut IN ('EN_ATTENTE', 'ACTIF'))
);

-- Recherche des inscriptions interrompues par la tâche de nettoyage : index partiel, limité aux comptes en attente
CREATE INDEX idx_utilisateur_en_attente ON utilisateur (date_creation) WHERE statut = 'EN_ATTENTE';
