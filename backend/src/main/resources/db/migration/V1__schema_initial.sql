-- Schéma initial StageHub (phase 1).
-- Hibernate tourne en ddl-auto=validate : ce script est la seule source de vérité du schéma.

CREATE TABLE utilisateur (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(255) NOT NULL,
    mot_de_passe   VARCHAR(100) NOT NULL,
    role           VARCHAR(20)  NOT NULL,
    date_creation  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_utilisateur_email UNIQUE (email),
    CONSTRAINT ck_utilisateur_role CHECK (role IN ('ETUDIANT', 'ENTREPRISE', 'ADMIN'))
);

-- Clé primaire partagée avec utilisateur (@OneToOne + @MapsId) : etudiant.id = utilisateur.id
CREATE TABLE etudiant (
    id         BIGINT       PRIMARY KEY REFERENCES utilisateur (id) ON DELETE CASCADE,
    nom        VARCHAR(100) NOT NULL,
    prenom     VARCHAR(100) NOT NULL,
    ecole      VARCHAR(150) NOT NULL,
    filiere    VARCHAR(150) NOT NULL,
    ville      VARCHAR(100) NOT NULL,
    chemin_cv  VARCHAR(500)
);

CREATE TABLE entreprise (
    id                 BIGINT       PRIMARY KEY REFERENCES utilisateur (id) ON DELETE CASCADE,
    nom                VARCHAR(150) NOT NULL,
    secteur            VARCHAR(100) NOT NULL,
    ville              VARCHAR(100) NOT NULL,
    description        TEXT,
    statut_validation  VARCHAR(20)  NOT NULL,
    CONSTRAINT ck_entreprise_statut_validation CHECK (statut_validation IN ('EN_ATTENTE', 'VALIDEE', 'REFUSEE'))
);

CREATE INDEX idx_entreprise_statut_validation ON entreprise (statut_validation);

CREATE TABLE offre (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre          VARCHAR(150) NOT NULL,
    description    TEXT         NOT NULL,
    ville          VARCHAR(100) NOT NULL,
    domaine        VARCHAR(100) NOT NULL,
    duree_mois     INTEGER      NOT NULL,
    date_limite    DATE         NOT NULL,
    statut         VARCHAR(20)  NOT NULL,
    entreprise_id  BIGINT       NOT NULL REFERENCES entreprise (id),
    CONSTRAINT ck_offre_duree_mois CHECK (duree_mois BETWEEN 1 AND 12),
    CONSTRAINT ck_offre_statut CHECK (statut IN ('OUVERTE', 'FERMEE'))
);

CREATE INDEX idx_offre_statut ON offre (statut);
CREATE INDEX idx_offre_entreprise ON offre (entreprise_id);

-- @ElementCollection Set<String> technologies
CREATE TABLE offre_technologie (
    offre_id     BIGINT      NOT NULL REFERENCES offre (id) ON DELETE CASCADE,
    technologie  VARCHAR(50) NOT NULL,
    PRIMARY KEY (offre_id, technologie)
);

CREATE TABLE candidature (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    etudiant_id        BIGINT      NOT NULL REFERENCES etudiant (id),
    offre_id           BIGINT      NOT NULL REFERENCES offre (id),
    lettre_motivation  TEXT,
    statut             VARCHAR(20) NOT NULL,
    date_candidature   TIMESTAMP WITH TIME ZONE NOT NULL,
    score_matching     INTEGER,
    CONSTRAINT uk_candidature_etudiant_offre UNIQUE (etudiant_id, offre_id),
    CONSTRAINT ck_candidature_statut CHECK (statut IN ('EN_ATTENTE', 'ENTRETIEN', 'ACCEPTEE', 'REFUSEE')),
    CONSTRAINT ck_candidature_score CHECK (score_matching BETWEEN 0 AND 100)
);

CREATE INDEX idx_candidature_offre ON candidature (offre_id);
