-- Phase 4 : journal d'audit (spec §3), alimenté par l'aspect AuditAspect.
-- Écrit dans la même transaction que l'action auditée : un rollback annule aussi la ligne d'audit.
CREATE TABLE audit_log (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action           VARCHAR(50)  NOT NULL,
    utilisateur      VARCHAR(255) NOT NULL,
    entite           VARCHAR(30)  NOT NULL,
    entite_id        BIGINT       NOT NULL,
    ancienne_valeur  VARCHAR(255),
    nouvelle_valeur  VARCHAR(255),
    date             TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Historique d'une entité donnée, et lecture du journal du plus récent au plus ancien
CREATE INDEX idx_audit_log_entite ON audit_log (entite, entite_id);
CREATE INDEX idx_audit_log_date ON audit_log (date DESC);
